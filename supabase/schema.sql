-- Створення замовлення. Ціни рахуються тут, на сервері, а не беруться з браузера.
create or replace function public.create_order(
  p_name text, p_phone text, p_delivery text, p_address text,
  p_comment text, p_items jsonb, p_payment text
) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_items jsonb := '[]'::jsonb;
  v_total numeric := 0;
  v_row record;
  v_it jsonb;
  v_qty int;
  v_number text;
begin
  if length(trim(coalesce(p_name,''))) < 2 or length(p_name) > 80 then raise exception 'bad name'; end if;
  if length(regexp_replace(coalesce(p_phone,''), '\D', '', 'g')) not between 10 and 13 then raise exception 'bad phone'; end if;
  if p_delivery not in ('pickup','delivery') then raise exception 'bad delivery'; end if;
  if p_delivery = 'delivery' and length(trim(coalesce(p_address,''))) < 5 then raise exception 'bad address'; end if;
  if p_payment not in ('cash','online') then raise exception 'bad payment'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 40 then raise exception 'bad items'; end if;

  -- Захист від спаму: не більше 5 замовлень з одного номера за 10 хвилин
  if (select count(*) from orders where phone = p_phone and created_at > now() - interval '10 minutes') >= 5 then
    raise exception 'too many orders';
  end if;

  for v_it in select * from jsonb_array_elements(p_items) loop
    v_qty := least(99, greatest(1, coalesce((v_it->>'qty')::int, 1)));
    select id, name, price into v_row from products where id = (v_it->>'id')::bigint and available;
    if not found then raise exception 'unavailable item'; end if;
    v_items := v_items || jsonb_build_object('id', v_row.id, 'name', v_row.name, 'price', v_row.price, 'qty', v_qty, 'sum', v_row.price * v_qty);
    v_total := v_total + v_row.price * v_qty;
  end loop;

  v_number := 'PM-' || to_char(now() at time zone 'Europe/Kyiv', 'YYMMDD-HH24MISS') || upper(substr(md5(random()::text), 1, 2));

  insert into orders (number, name, phone, delivery, address, comment, items, total, payment_method, payment_status)
  values (v_number, trim(p_name), trim(p_phone), p_delivery,
          case when p_delivery = 'delivery' then left(trim(coalesce(p_address,'')), 200) else '' end,
          left(trim(coalesce(p_comment,'')), 500), v_items, v_total, p_payment,
          case when p_payment = 'online' then 'pending' else 'unpaid' end);

  return json_build_object('number', v_number, 'total', v_total);
end $$;

-- Статус оплати для сторінки «дякуємо» (без особистих даних)
create or replace function public.order_status(p_number text) returns json
language sql security definer stable set search_path = public as $$
  select json_build_object('number', number, 'payment_status', payment_status, 'payment_method', payment_method, 'total', total)
  from orders where number = p_number;
$$;

grant execute on function public.create_order(text,text,text,text,text,jsonb,text) to anon, authenticated;
grant execute on function public.order_status(text) to anon, authenticated;

