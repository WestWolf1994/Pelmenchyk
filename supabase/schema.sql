-- Адміністратори (хто має право заходити в адмінку)
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean
language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- Категорії та страви
create table if not exists public.categories (
  id text primary key,
  name text not null,
  bg text not null default '#E4CBA8',
  image text not null default '',
  art text not null default 'pelmeni',
  sauce text not null default '#FFFDF8',
  sort int not null default 0
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text references public.categories(id) on update cascade on delete set null,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  weight text not null default '',
  image text not null default '',
  art text not null default 'pelmeni',
  sauce text not null default '#FFFDF8',
  available boolean not null default true,
  sort int not null default 0
);

-- Налаштування сайту: контакти, посилання, тексти «Про нас»
create table if not exists public.settings (
  key text primary key,
  value text not null default ''
);

-- Замовлення
create table if not exists public.orders (
  id bigint generated always as identity primary key,
  number text unique not null,
  created_at timestamptz not null default now(),
  name text not null,
  phone text not null,
  delivery text not null check (delivery in ('pickup','delivery')),
  address text not null default '',
  comment text not null default '',
  items jsonb not null,
  total numeric(10,2) not null,
  payment_method text not null check (payment_method in ('cash','online')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending','paid','failed')),
  status text not null default 'new' check (status in ('new','confirmed','cooking','done','cancelled'))
);
create index if not exists orders_created_idx on public.orders (created_at desc);

